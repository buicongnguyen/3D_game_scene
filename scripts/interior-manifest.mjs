// Where things are inside each room model, read from the GLBs in public/models, so the game knows its doors, residents,
// keepsakes and bounds before a room's model has been downloaded (the rooms are fetched when the player comes near a door).
// Writes src/content/interior-manifest.js. `node scripts/interior-manifest.mjs`; tests/interior-manifest.test.mjs fails when
// the file no longer matches the models.
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const NODE_RE = /^(Spawn|Exit|Item_|Light_|Gear_|Pendulum|Spot_)/;
const r6 = v => Math.round(v * 1e6) / 1e6;

// 4x4 column-major helpers (glTF matrices)
function applyPoint(m, [x, y, z]) { return [m[0] * x + m[4] * y + m[8] * z + m[12], m[1] * x + m[5] * y + m[9] * z + m[13], m[2] * x + m[6] * y + m[10] * z + m[14]]; }
function quatFromMatrix(m) {
  // rotation part with scale removed
  const sx = Math.hypot(m[0], m[1], m[2]), sy = Math.hypot(m[4], m[5], m[6]), sz = Math.hypot(m[8], m[9], m[10]);
  const a = m[0] / sx, b = m[4] / sy, c = m[8] / sz, d = m[1] / sx, e = m[5] / sy, f = m[9] / sz, g = m[2] / sx, h = m[6] / sy, i = m[10] / sz;
  const tr = a + e + i;
  let x, y, z, w;
  if (tr > 0) { const s = 0.5 / Math.sqrt(tr + 1); w = 0.25 / s; x = (h - f) * s; y = (c - g) * s; z = (d - b) * s; }
  else if (a > e && a > i) { const s = 2 * Math.sqrt(1 + a - e - i); w = (h - f) / s; x = 0.25 * s; y = (b + d) / s; z = (c + g) / s; }
  else if (e > i) { const s = 2 * Math.sqrt(1 + e - a - i); w = (c - g) / s; x = (b + d) / s; y = 0.25 * s; z = (f + h) / s; }
  else { const s = 2 * Math.sqrt(1 + i - a - e); w = (d - b) / s; x = (c + g) / s; y = (f + h) / s; z = 0.25 * s; }
  return [x, y, z, w];
}
function boxIn(node) {
  const prim = node.getMesh()?.listPrimitives()[0], acc = prim?.getAttribute('POSITION');
  if (!acc) return null;
  const mn = acc.getMin([]), mx = acc.getMax([]), m = node.getWorldMatrix();
  const lo = [1e9, 1e9, 1e9], hi = [-1e9, -1e9, -1e9];
  for (const x of [mn[0], mx[0]]) for (const y of [mn[1], mx[1]]) for (const z of [mn[2], mx[2]]) {
    const p = applyPoint(m, [x, y, z]);
    for (let k = 0; k < 3; k++) { lo[k] = Math.min(lo[k], p[k]); hi[k] = Math.max(hi[k], p[k]); }
  }
  return { min: lo.map(r6), max: hi.map(r6) };
}

export async function buildManifest(dir = path.join(root, 'public/models')) {
  const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
  const out = {};
  for (const f of readdirSync(dir).filter(n => /^interior-.*\.glb$/.test(n)).sort()) {
    const doc = await io.read(path.join(dir, f));
    const nodes = {}, entry = { nodes, floor: null, ceilingMinY: null };
    const seen = new Set();
    const visit = n => {
      const name = n.getName();
      if (NODE_RE.test(name)) {
        if (seen.has(name)) throw new Error(`${f}: node ${name} appears twice`);
        seen.add(name);
        const m = n.getWorldMatrix();
        nodes[name] = { p: applyPoint(m, [0, 0, 0]).map(r6), q: quatFromMatrix(m).map(r6), x: n.getExtras() && Object.keys(n.getExtras()).length ? n.getExtras() : undefined };
        if (nodes[name].x === undefined) delete nodes[name].x;
      }
      if (name === 'Col_floor') entry.floor = boxIn(n);
      if (name === 'Col_ceiling') { const b = boxIn(n); if (b) entry.ceilingMinY = b.min[1]; }
      n.listChildren().forEach(visit);
    };
    doc.getRoot().getDefaultScene().listChildren().forEach(visit);
    out[f.replace(/\.glb$/, '')] = entry;
  }
  return out;
}

export function render(manifest) {
  return `// Generated by scripts/interior-manifest.mjs from public/models/interior-*.glb. Do not edit.\n// Room-model space: p = position, q = rotation (x, y, z, w), x = the node's extras.\nexport const INTERIOR_MANIFEST = ${JSON.stringify(manifest, null, 1)};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const m = await buildManifest();
  writeFileSync(path.join(root, 'src/content/interior-manifest.js'), render(m));
  console.log('interior manifest:', Object.keys(m).length, 'rooms');
}
