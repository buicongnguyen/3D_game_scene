// The far views of the play zones (docs/PLAY-ZONES-PLAN.md, world/zone-backdrop.js): for every converted game in
// content/zones.js, the whole valley is loaded at the game's own season and hour (no weather, nobody about) and a cube
// of six pictures is taken from the zone's middle with the near plane at the zone's edge (src/dev/backdrop-bake.js).
// Writes public/zones/<game>/{px,nx,py,ny,pz,nz}.webp and src/content/zone-backdrops.js (what the game reads).
//   npm run build && npx vite preview --port 5897 --strictPort   (in another shell)
//   GAME_URL=http://127.0.0.1:5897/ node scripts/bake-zone-backdrops.mjs [--games=trick:eggs] [--size=768]
// Bake again when the valley changes around a zone (tests/zone.test.mjs checks every zone has its files).
import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ZONES, zoneFor } from '../src/content/zones.js';
import { buildCatalogue, launchPlan } from '../src/content/minigames.js';
import { exploreState } from '../src/game/fastforward.js';
import { BAND } from '../src/world/zone-backdrop.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = Object.fromEntries(process.argv.slice(2).map(a => { const s = a.replace(/^--/, ''), i = s.indexOf('='); return i < 0 ? [s, ''] : [s.slice(0, i), s.slice(i + 1)]; }));
const url = process.env.GAME_URL || 'http://127.0.0.1:5897/';
const SIZE = +(args.size || 768), SCALE = 0.5, EYE = 4;
const games = args.games ? args.games.split(',') : Object.keys(ZONES);
const FACES = ['px', 'nx', 'py', 'ny', 'pz', 'nz'];
const catalogue = buildCatalogue();
const SAVE = JSON.stringify({ v: 1, quest: exploreState(), player: { x: -45, y: 4, z: 27, facing: Math.PI }, at: 1760000000000 });
const metaFile = path.join(root, 'src/content/zone-backdrops.js');
const meta = fs.existsSync(metaFile) ? (await import(`file://${metaFile.replace(/\\/g, '/')}?t=${Date.now()}`)).BACKDROPS : {};

const browser = await chromium.launch({ headless: true, args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist', '--mute-audio'] });
for (const id of games) {
  const z = zoneFor(id), e = catalogue.find(c => c.id === id);
  if (!z || !e) { console.warn(`no zone for ${id}`); continue; }
  const plan = launchPlan(e);
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 } });
  await ctx.addInitScript(s => localStorage.setItem('starline-save-explore', s), SAVE);
  const page = await ctx.newPage();
  page.on('pageerror', err => console.warn('  page error:', err.message));
  await page.goto(`${url}?mute&qa=1&quality=high&quick=off&start=explore&slot=explore`);
  await page.waitForFunction(() => window.__STARLINE_PLAYING__ && window.__STARLINE_QA__?.bakeBackdrop, null, { timeout: 240000 });
  // the game's look; nobody about (the zone has its own people), no weather or loose particles
  const y = await page.evaluate(([x, zz, season, hour]) => {
    const g = window.__STARLINE__;
    g.seasonOverride = season; g.timeOverride = hour; g.cycleHour = undefined; g.weatherOff = true; g.applyLook();
    window.__STARLINE_QA__.teleport(x, zz);
    return g.world.heightAt(x, zz);
  }, [z.x, z.z, plan.season, plan.hour]);
  await page.waitForTimeout(2500);                       // lamps, sky and the day's light settle
  await page.evaluate(() => {
    const g = window.__STARLINE__;
    for (const c of g.scene.children) if (/^(npc:|critter:|player|tamo)/.test(c.name || '') || c.isPoints || c.isSprite) c.visible = false;
  });
  // two sizes: SIZE for the Low tier (phones), twice that in hd/ for Medium and High
  const sizes = [];
  for (const [size, sub] of [[SIZE, ''], [SIZE * 2, 'hd']]) {
    const faces = await page.evaluate(o => window.__STARLINE_QA__.bakeBackdrop(o), { x: z.x, y: y + EYE, z: z.z, near: (z.r - BAND) * 0.55, inside: z.r, size, scale: SCALE });
    const dir = path.join(root, 'public/zones', id.replace(':', '_'), sub);
    fs.mkdirSync(dir, { recursive: true });
    let bytes = 0;
    faces.forEach((d, i) => { const b = Buffer.from(d.split(',')[1], 'base64'); bytes += b.length; fs.writeFileSync(path.join(dir, `${FACES[i]}.webp`), b); });
    sizes.push(`${size} px ${(bytes / 1024).toFixed(0)} kB`);
  }
  meta[id] = { dir: `zones/${id.replace(':', '_')}/`, y: +(y + EYE).toFixed(2), near: +((z.r - BAND) * 0.55).toFixed(1), size: SIZE, hd: SIZE * 2, scale: SCALE, season: plan.season, hour: plan.hour };
  console.log(`${id}: ${sizes.join(', ')} (${plan.season}, ${plan.hour} h)`);
  await ctx.close();
}
await browser.close();
const body = Object.entries(meta).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  '${k}': ${JSON.stringify(v)},`).join('\n');
fs.writeFileSync(metaFile, `// Generated by scripts/bake-zone-backdrops.mjs: the far view baked for each play zone (public/zones/).\n// scale: the faces hold the light times this (drawn at 1 / scale). season, hour: the look they were taken in.\nexport const BACKDROPS = {\n${body}\n};\n`);
console.log(`written ${path.relative(root, metaFile)}`);
